@bot.on_message()
async def handle_message(message: Message):

    user_id = message.user.id
    text = message.text or ""

    print(f"📩 User {user_id}: {repr(text)}")

    add_user(user_id)

    owner = is_owner(user_id)


    # =====================================================
    # ارسال همگانی
    # =====================================================

    if owner and user_id in broadcast_mode:

        if "بازگشت" in text:

            broadcast_mode.discard(user_id)

            await message.reply(
                "❌ ارسال همگانی لغو شد.",
                reply_markup=admin_keyboard()
            )

            return

        users = load_users()

        await message.reply(
            f"📢 ارسال برای {len(users)} کاربر شروع شد..."
        )

        sent = 0
        failed = 0

        for target_id in users:

            try:

                await bot.send_message(
                    target_id,
                    text
                )

                sent += 1

                await asyncio.sleep(0.1)

            except Exception as e:

                failed += 1

                print(
                    "خطا در ارسال:",
                    target_id,
                    e
                )

        broadcast_mode.discard(user_id)

        await message.reply(
            f"""✅ ارسال تمام شد.

📨 موفق: {sent}
❌ ناموفق: {failed}
👥 کل کاربران: {len(users)}""",
            reply_markup=admin_keyboard()
        )

        return


    # =====================================================
    # START
    # =====================================================

    if text.startswith("/start"):

        joined = await is_member(user_id)

        if not joined:

            await message.reply(
                JOIN_TEXT,
                reply_markup=join_keyboard()
            )

            return

        await message.reply(
            WELCOME_TEXT,
            reply_markup=main_keyboard()
        )

        return


    # =====================================================
    # ADMIN
    # =====================================================

    if text == "/admin":

        if not owner:

            await message.reply(
                "⛔️ این قسمت فقط برای صاحب رباته."
            )

            return

        await message.reply(
            "👑 پنل مدیریت سیمبل نارومی",
            reply_markup=admin_keyboard()
        )

        return


    # =====================================================
    # آمار
    # =====================================================

    if "آمار کاربران" in text:

        if not owner:
            return

        users = load_users()

        await message.reply(
            f"📊 تعداد کاربران ربات: {len(users)}"
        )

        return


    # =====================================================
    # ارسال همگانی
    # =====================================================

    if "ارسال همگانی" in text:

        if not owner:
            return

        broadcast_mode.add(user_id)

        await message.reply(
            """📢 آماده دریافت پیامم!

هر چیزی که پیام بعدی بفرستی،
برای تمام کاربران ربات ارسال میشه.

برای لغو:
🔙 بازگشت"""
        )

        return


    # =====================================================
    # بازگشت
    # =====================================================

    if "بازگشت" in text:

        if owner:

            broadcast_mode.discard(user_id)

            await message.reply(
                WELCOME_TEXT,
                reply_markup=main_keyboard()
            )

        return


    # =====================================================
    # دکمه‌های سیمبل
    # =====================================================

    if "سیمبل تکی" in text:

        await message.reply(
            SINGLE_SYMBOL
        )

        return


    if "سیمبل ریسه" in text:

        await message.reply(
            GARLAND_SYMBOL
        )

        return


    if "سیمبل نامرئی" in text:

        await message.reply(
            INVISIBLE_SYMBOL
        )

        return


    if "سيمبل ايموجي" in text:

        await message.reply(
            EMOJI_SYMBOL
        )

        return


    if "سیمبل شکلی" in text:

        await message.reply(
            SHAPELY_SYMBOL
        )

        return


    if "ابزار ادیت" in text:

        await message.reply(
            EDIT_TOOLS_TEXT
        )

        return


    if "گزینه مهم" in text:

        await message.reply(
            IMPORTANT_OPTION_TEXT
        )

        return


    if "چنل سیمبل و پیک" in text:

        await message.reply(
            SYMBOL_PICK_CHANNEL_TEXT
        )

        return


    if "بیوگرافی" in text:

        await message.reply(
            BIOGRAPHY_TEXT
        )

        return


    if "ارتباط با ما" in text:

        await message.reply(
            CONTACT_TEXT
        )

        return


